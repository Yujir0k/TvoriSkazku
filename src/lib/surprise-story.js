const GENRES = ['Сказка', 'Фэнтези', 'Приключение', 'Детектив', 'Научная фантастика', 'Притча', 'Юмор'];

function pick(items, random) {
  return items[Math.floor(random() * items.length) % items.length];
}

export function createSurpriseStory(random = Math.random, previousIdeas = new Set()) {
  let result;
  for (let attempt = 0; attempt < 12; attempt += 1) {
    const hero = pick(HEROES, random);
    const companion = pick(COMPANIONS, random);
    const [location, place] = pick(PLACES, random);
    const discovery = pick(DISCOVERIES, random);
    const mission = pick(MISSIONS, random);
    const obstacle = pick(OBSTACLES, random);
    const lengthRoll = random();

    const sentences = [
      `Однажды ${hero} оказывается ${place} и ${discovery}.`,
      `Вместе с героем отправляется ${companion}: друзьям нужно ${mission}, но ${obstacle}.`,
    ];
    if (lengthRoll >= 0.34) sentences.push(pick(TWISTS, random));
    if (lengthRoll >= 0.72) sentences.push(pick(ENDINGS, random));

    result = {
      idea: sentences.join(' '),
      genre: pick(GENRES, random),
      location,
    };
    if (!previousIdeas.has(result.idea)) return result;
  }
  return result;
}
